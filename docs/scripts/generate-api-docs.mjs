#!/usr/bin/env node
/**
 * Generate VitePress markdown API reference from @stambha/* package sources.
 *
 * Usage: node scripts/generate-api-docs.mjs
 * Requires: pnpm build (or valid package sources + tsconfig per package)
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const docsRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(docsRoot, "..");

/** npm name → output folder under docs/api/ */
const API_PACKAGES = [
  { dir: "core", name: "@stambha/core" },
  { dir: "loader", name: "@stambha/loader" },
  { dir: "gates", name: "@stambha/gates" },
  { dir: "vault", name: "@stambha/vault" },
  { dir: "rest", name: "@stambha/rest" },
  { dir: "gateway", name: "@stambha/gateway" },
  { dir: "transform", name: "@stambha/transform" },
  { dir: "args", name: "@stambha/args" },
  { dir: "authz", name: "@stambha/authz" },
  { dir: "plugins", name: "@stambha/plugins" },
  { dir: "help", name: "@stambha/help" },
  { dir: "transport", name: "@stambha/transport" },
];

const typedocBin = path.join(
  docsRoot,
  "node_modules",
  "typedoc",
  "bin",
  "typedoc",
);

function rimraf(dir) {
  if (fs.existsSync(dir)) {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

function resolveTypedocTsconfig(pkgDir) {
  return path.join(repoRoot, "packages", pkgDir, "tsconfig.json");
}

function runTypeDoc(pkg) {
  const entry = path.join(repoRoot, "packages", pkg.dir, "src", "index.ts");
  const tsconfig = resolveTypedocTsconfig(pkg.dir);
  const out = path.join(docsRoot, "api", pkg.dir);

  if (!fs.existsSync(entry)) {
    console.warn(`skip ${pkg.name}: missing ${entry}`);
    return false;
  }

  rimraf(out);
  fs.mkdirSync(out, { recursive: true });

  console.log(`generating ${pkg.name} → docs/api/${pkg.dir}/`);

  execFileSync(
    process.execPath,
    [
      typedocBin,
      "--entryPoints",
      entry,
      "--out",
      out,
      "--tsconfig",
      tsconfig,
      "--name",
      pkg.name,
      "--readme",
      "none",
      "--plugin",
      "typedoc-plugin-markdown",
      "--entryFileName",
      "index",
      "--hidePageHeader",
      "true",
      "--hideBreadcrumbs",
      "true",
      "--exclude",
      "**/*.test.ts",
      "--exclude",
      "**/*.spec.ts",
      "--excludePrivate",
      "--excludeInternal",
      "--skipErrorChecking",
      "--logLevel",
      "Error",
      "--sourceLinkTemplate",
      "https://github.com/mivaya/Stambha/blob/main/{path}#L{line}",
    ],
    {
      cwd: docsRoot,
      stdio: "inherit",
    },
  );

  prependFrontmatter(out);
  return true;
}

/** VitePress doc layout for generated pages. */
function prependFrontmatter(outDir) {
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
        continue;
      }
      if (!entry.name.endsWith(".md")) continue;
      const raw = fs.readFileSync(full, "utf8");
      if (raw.startsWith("---")) continue;
      fs.writeFileSync(full, `---\nlayout: doc\n---\n\n${raw}`);
    }
  };
  walk(outDir);
}

function writeApiSidebar(generated) {
  const sidebarPath = path.join(docsRoot, ".vitepress", "sidebars", "api.ts");
  const packageItems = generated
    .map(
      (pkg) =>
        `      { text: "${pkg.name}", link: "/api/${pkg.dir}/" },`,
    )
    .join("\n");

  const content = `import type { DefaultTheme } from "vitepress";

/** Auto-generated by scripts/generate-api-docs.mjs — do not edit by hand. */
export const apiSidebar: DefaultTheme.SidebarItem[] = [
  {
    text: "API Reference",
    items: [{ text: "Overview", link: "/api/" }],
  },
  {
    text: "Packages",
    collapsed: false,
    items: [
${packageItems}
    ],
  },
  {
    text: "Related",
    items: [
      { text: "Transport map", link: "/reference/transport" },
      {
        text: "Package source on GitHub",
        link: "https://github.com/mivaya/Stambha/tree/main/packages",
        process: false,
      },
    ],
  },
];
`;

  fs.writeFileSync(sidebarPath, content);
  console.log("updated .vitepress/sidebars/api.ts");
}

function removeLegacyStubs() {
  for (const pkg of API_PACKAGES) {
    const dir = path.join(docsRoot, "api", pkg.dir);
    if (!fs.existsSync(dir)) continue;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isFile() && entry.name.endsWith(".md") && entry.name !== "index.md") {
        fs.unlinkSync(path.join(dir, entry.name));
      }
    }
  }
}

function main() {
  if (!fs.existsSync(typedocBin)) {
    console.error("typedoc not found — run pnpm install in docs/");
    process.exit(1);
  }

  const ifMissing = process.argv.includes("--if-missing");
  const coreIndex = path.join(docsRoot, "api", "core", "index.md");
  if (ifMissing && fs.existsSync(coreIndex)) {
    console.log("API reference already generated — skip (run pnpm docs:api to refresh)");
    return;
  }

  removeLegacyStubs();

  const generated = [];
  for (const pkg of API_PACKAGES) {
    if (runTypeDoc(pkg)) generated.push(pkg);
  }

  if (generated.length === 0) {
    console.error("no API packages generated");
    process.exit(1);
  }

  writeApiSidebar(generated);
  console.log(`done — ${generated.length} package(s)`);
}

main();
